initialize_rice_theme() {
    local app_dir="$config_home/rice-theme" selector="$selectors_dir/profile"
    local name temp
    [[ "$(readlink -f -- "$app_dir" 2>/dev/null)" == "$repo_dir/config/rice-theme" ]] || return
    [[ -e "$selector" || -L "$selector" ]] && { ok "desktop profile already initialized"; return; }
    [[ -r "$app_dir/default-profile" ]] || { fail 'missing default desktop profile'; return; }
    IFS= read -r name < "$app_dir/default-profile"
    [[ "$name" =~ ^[A-Za-z0-9_-]+$ && -f "$app_dir/profiles/$name" ]] || {
        fail "invalid default desktop profile: $name"
        return
    }
    temp=$(mktemp "$selectors_dir/.profile.XXXXXX") || { fail 'could not create desktop profile selector'; return; }
    printf '%s\n' "$name" > "$temp"
    mv -- "$temp" "$selector"
    ok "initialized desktop profile: $name"
}

migrate_theme_selector() {
    local kind="$1" old_selector="$2" selector="$3" app_dir="$4" managed_dir="$5"
    local name theme_path temp
    [[ "$(readlink -f -- "$app_dir" 2>/dev/null)" == "$managed_dir" ]] || return
    [[ -f "$old_selector" && ! -e "$selector" && ! -L "$selector" ]] || return
    case "$kind" in
        Hyprland)
            name=$(sed -n 's|^[[:space:]]*source[[:space:]]*=[[:space:]]*.*themes/\([A-Za-z0-9_-]*\)\.conf[[:space:]]*$|\1|p' "$old_selector")
            theme_path="$app_dir/themes/$name.conf"
            ;;
        Kitty)
            theme_path=$(awk '$1 == "include" { print $2; exit }' "$old_selector")
            name=$(basename "${theme_path:-}" .conf)
            [[ "$name" == black ]] && name=ghost-shell
            theme_path="$app_dir/themes/$name.conf"
            ;;
        Rofi)
            theme_path=$(sed -n 's/^@theme[[:space:]]*"\(.*\)"$/\1/p' "$old_selector")
            name=$(basename "$(dirname "${theme_path:-/}")")
            [[ "$name" == ghost-v2 ]] && name=ghost-shell
            theme_path="$app_dir/themes/$name/theme.rasi"
            ;;
        Waybar|SwayNC)
            name=$(sed -n 's|^@import url("themes/\([A-Za-z0-9_-]*\)\.css");$|\1|p' "$old_selector")
            theme_path="$app_dir/themes/$name.css"
            ;;
    esac
    [[ "$name" =~ ^[A-Za-z0-9_-]+$ && -f "$theme_path" ]] || {
        warn "could not migrate invalid $kind selector: $old_selector"
        return
    }
    temp=$(mktemp "$selectors_dir/.selector.XXXXXX") || { fail "could not migrate $kind selector"; return; }
    case "$kind" in
        Hyprland) printf 'source = %s\n' "$theme_path" > "$temp" ;;
        Kitty) printf '%s\n' '# Local theme selection; generated by setup.sh or kitty-theme.' "include $theme_path" > "$temp" ;;
        Rofi) printf '@theme "%s"\n' "$theme_path" > "$temp" ;;
        Waybar) printf '@import url("../../waybar/themes/%s.css");\n' "$name" > "$temp" ;;
        SwayNC) printf '@import url("../../swaync/themes/%s.css");\n' "$name" > "$temp" ;;
    esac
    if mv -- "$temp" "$selector" && rm -f -- "$old_selector"; then
        ok "migrated $kind selector to $selector"
    else
        rm -f -- "$temp"
        fail "could not migrate $kind selector"
    fi
}

migrate_local_selectors() {
    migrate_theme_selector Hyprland "$config_home/hypr/local-theme.conf" "$selectors_dir/hyprland.conf" "$config_home/hypr" "$repo_dir/config/hypr"
    migrate_theme_selector Kitty "$config_home/kitty/local-theme.conf" "$selectors_dir/kitty.conf" "$config_home/kitty" "$repo_dir/config/kitty"
    migrate_theme_selector Rofi "$config_home/rofi/local-theme.rasi" "$selectors_dir/rofi.rasi" "$config_home/rofi" "$repo_dir/config/rofi"
    migrate_theme_selector Waybar "$config_home/waybar/local-theme.css" "$selectors_dir/waybar.css" "$config_home/waybar" "$repo_dir/config/waybar"
    migrate_theme_selector SwayNC "$config_home/swaync/local-theme.css" "$selectors_dir/swaync.css" "$config_home/swaync" "$repo_dir/config/swaync"
    if [[ -f "$config_home/rice-theme/local-profile" && ! -e "$selectors_dir/profile" ]]; then
        if mv -- "$config_home/rice-theme/local-profile" "$selectors_dir/profile"; then
            ok "migrated desktop profile selector to $selectors_dir/profile"
        else
            fail 'could not migrate desktop profile selector'
        fi
    fi
}

check_command() {
    local command_name="$1" feature="$2"
    if command -v "$command_name" >/dev/null 2>&1; then
        ok "$command_name ($feature)"
    else
        warn "missing command: $command_name ($feature)"
        missing=$((missing + 1))
    fi
}

